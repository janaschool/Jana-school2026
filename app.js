const $=s=>document.querySelector(s);
const $$=s=>[...document.querySelectorAll(s)];
let done=new Set(JSON.parse(localStorage.getItem('g9done')||'[]'));
let quiz=null, qi=0, score=0;

function show(id){
  $$('.view').forEach(v=>v.classList.remove('active'));
  $('#'+id).classList.add('active');
  $$('nav button').forEach(b=>b.classList.toggle('active',b.dataset.view===id));
  window.scrollTo(0,0);
}

function progress(){
  const p=Math.round(done.size/D.length*100);
  $('#progressText').textContent=p+'%';
  $('#progressBar').style.width=p+'%';
}

function subjects(){
  $('#subjects').innerHTML=D.map(x=>`
    <article class="subject" onclick="openLesson('${x.id}')">
      <div class="icon">${x.i}</div>
      <h3>${x.s}</h3>
      <p>${x.t}</p>
      <span class="tag">${done.has(x.id)?'✓ مكتمل':'ابدئي الدرس'}</span>
    </article>`).join('');
}

function lessons(){
  const f=$('#filter').value;
  const list=f==='all'?D:D.filter(x=>x.id===f);
  $('#lessonGrid').innerHTML=list.map(x=>`
    <article class="lesson-card">
      <div class="icon">${x.i}</div>
      <small>${x.s}</small>
      <h3>${x.t}</h3>
      <p>${x.d}</p>
      <button class="primary" onclick="openLesson('${x.id}')">فتح الدرس</button>
      <button onclick="startQuiz('${x.id}')">اختبار</button>
    </article>`).join('');
}

function openLesson(id){
  const x=D.find(a=>a.id===id);
  let activity='';
  if(x.id==='chemistry'){
    activity=`<input id="ph" type="range" min="0" max="14" value="7" style="width:90%"><h3>pH = <span id="phv">7</span></h3><div id="phr" class="panel">متعادل</div>`;
  }else if(x.id==='biology'){
    activity=`<div class="activity">${['النواة','الميتوكندريا','الريبوسومات','أجسام غولجي'].map(a=>`<button onclick="$('#bio').textContent='${a}: '+bioInfo('${a}')">${a}</button>`).join('')}</div><p id="bio" class="panel">اضغطي على عضية.</p>`;
  }else if(x.id==='earth'){
    activity=`<select onchange="earthInfo(this.value)"><option value="">اختاري العامل</option><option value="s">انحدار شديد</option><option value="t">أشجار كثيفة</option><option value="r">صخور كتيمة</option><option value="a">تربة رملية</option></select><p id="earth"></p>`;
  }else if(x.id==='physics'){
    activity=`<p>عدم تصفير الميزان قبل القياس:</p><div class="activity"><button onclick="phys('منتظم')">منتظم</button><button onclick="phys('عشوائي')">عشوائي</button></div><p id="phys"></p>`;
  }else{
    activity=`<p>راجعي النقاط أعلاه ثم جربي الاختبار القصير.</p>`;
  }

  $('#detail').innerHTML=`
    <div class="detail-head"><div class="icon">${x.i}</div><small>${x.s}</small><h2>${x.t}</h2><p>${x.intro}</p></div>
    <div class="panel"><h3>🎯 أهداف التعلم</h3><ul>${x.o.map(a=>`<li>${a}</li>`).join('')}</ul></div>
    ${x.e.map(a=>`<div class="panel"><h3>${a[0]}</h3><p>${a[1]}</p></div>`).join('')}
    <div class="interactive"><h3>✨ نشاط تفاعلي</h3>${activity}</div>
    <div class="panel"><h3>📌 الخلاصة</h3><p>${x.sum}</p></div>
    <div style="text-align:center"><button class="primary" onclick="complete('${x.id}')">${done.has(x.id)?'✓ مكتمل':'وضع علامة كمكتمل'}</button> <button onclick="startQuiz('${x.id}')">ابدئي الاختبار</button></div>`;
  show('lesson');
}

function complete(id){
  done.add(id);
  localStorage.setItem('g9done',JSON.stringify([...done]));
  progress(); subjects(); lessons(); openLesson(id);
}

function bioInfo(a){
  return {'النواة':'مركز التحكم وتحوي DNA','الميتوكندريا':'إنتاج الطاقة','الريبوسومات':'بناء البروتينات','أجسام غولجي':'تغليف وإفراز المواد'}[a];
}
function earthInfo(v){$('#earth').textContent={s:'يزداد الجريان السطحي.',t:'يقل الجريان ويزداد التسرب.',r:'يزداد الجريان لعدم النفاذ.',a:'يقل الجريان ويزداد التسرب.'}[v]||'';}
function phys(v){$('#phys').textContent=v==='منتظم'?'إجابة صحيحة ✅':'إجابة غير صحيحة ❌';}

function startQuiz(id){
  quiz=D.find(x=>x.id===id); qi=0; score=0; show('quiz'); pick(); question();
}
function pick(){
  $('#quizPicker').innerHTML=D.map(x=>`<button onclick="startQuiz('${x.id}')">${x.i} ${x.s}</button>`).join('');
}
function question(){
  if(qi>=quiz.q.length){
    $('#quizArea').innerHTML=`<div class="quizbox" style="text-align:center"><h2>🎉 انتهى الاختبار</h2><p>نتيجتك في ${quiz.s}: <b>${score}/${quiz.q.length}</b></p><button class="primary" onclick="startQuiz('${quiz.id}')">إعادة الاختبار</button></div>`;
    return;
  }
  const q=quiz.q[qi];
  $('#quizArea').innerHTML=`<div class="quizbox"><small>السؤال ${qi+1} من ${quiz.q.length}</small><h3>${q[0]}</h3>${q[1].map((o,i)=>`<button class="option" onclick="answer(${i},${q[2]})">${o}</button>`).join('')}<p id="msg"></p><button id="next" class="primary" disabled onclick="qi++;question()">التالي</button></div>`;
}
function answer(i,c){
  const bs=$$('.option');
  bs.forEach((b,n)=>{b.disabled=true;if(n===c)b.classList.add('correct');if(n===i&&i!==c)b.classList.add('wrong')});
  $('#msg').textContent=i===c?'إجابة صحيحة ✅':'إجابة غير صحيحة ❌';
  if(i===c)score++;
  $('#next').disabled=false;
}

$$('nav button').forEach(b=>b.addEventListener('click',()=>show(b.dataset.view)));
$('#filter').addEventListener('change',lessons);
D.forEach(x=>$('#filter').insertAdjacentHTML('beforeend',`<option value="${x.id}">${x.s}</option>`));

document.addEventListener('input',e=>{
  if(e.target.id==='ph'){
    const v=+e.target.value;
    $('#phv').textContent=v;
    $('#phr').textContent=v<7?'حمضي 🔴':v>7?'قاعدي 🔵':'متعادل ⚪';
  }
});

subjects(); lessons(); pick(); progress();
